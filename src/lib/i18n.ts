export type I18nKey = keyof typeof i18n;

export function t(lang: Lang, key: I18nKey): string {
  const entry = i18n[key];
  return entry ? entry[lang] : key;
}

export function pick(lang: Lang, en: string, bg: string): string {
  return lang === "bg" ? bg : en;
}

export function countLabel(lang: Lang, n: number): string {
  return `${n} ${t(lang, "cat.products")}`;
}

export function searchCountLabel(lang: Lang, n: number): string {
  return `${n} ${n === 1 ? t(lang, "search.count.one") : t(lang, "search.count.many")}`;
}
